// TARS UI (F5): POST /api/assistant/ask, contract v0.2.0. Answers come only
// from the backend, are attributed to FlameGuard-SI (never NASA), show their
// mode and limitations, and cite findings. Isolated: model/ and the ranking
// view never import this module.

import { isNotImplemented } from "../api/errors.js";

import { exclusionContext, traceSupport } from "../model/trace.js";
import { evidenceBadge, fixtureBadge, sourceItem, statePanel } from "../ui/components.js";
import { h, mount } from "../ui/dom.js";

export const MODES = Object.freeze({
  ai: { label: "AI-generated answer", description: "Written by an AI model from retrieved evidence. Generated by FlameGuard-SI, not NASA." },
  fallback_quotes: { label: "Quotes only (no AI)", description: "Assembled from exact recorded source quotes, without an AI model." },
  no_evidence: { label: "No evidence found", description: "The assistant found no evidence for this question and makes no claim." },
});

/**
 * Display check on an assistant answer. Fails closed: any problem withholds
 * the whole answer. Classifies each citation as supporting evidence or as an
 * exclusion explanation (S9, transitive).
 * @param {import("../api/types.js").AssistantAnswer} res
 * @param {Map<string, import("../api/types.js").Finding>} findingsById
 */
export function reviewAnswer(res, findingsById = new Map()) {
  const problems = [];
  const citations = [];
  if (!res || typeof res.answer !== "string" || !res.answer.trim()) problems.push("Response has no answer text.");
  if (!res || res.generated_by !== "FlameGuard-SI") problems.push("Answer is not attributed to FlameGuard-SI.");
  if (!res || !Object.hasOwn(MODES, res.mode)) problems.push("Answer has no valid mode.");
  const cites = res && Array.isArray(res.citations) ? res.citations : [];
  const lims = res && Array.isArray(res.limitations) ? res.limitations : [];
  if (res && res.mode !== "no_evidence") {
    if (cites.length === 0) problems.push("Answer cites no findings.");
    if (lims.length === 0) problems.push("Answer states no limitations.");
  }
  for (const c of cites) {
    const f = findingsById.get(c.finding_id);
    if (!f) {
      problems.push(`Citation ${c.finding_id} does not resolve to a loaded finding.`);
      continue;
    }
    if (f.evidence_class !== c.evidence_class) problems.push(`Citation ${c.finding_id} is declared ${c.evidence_class} but the finding is ${f.evidence_class}.`);
    if (!c.source || !c.source.title) problems.push(`Citation ${c.finding_id} has no source.`);
    const exclusion = exclusionContext(f, findingsById);
    if (exclusion.length) {
      // S9: "TARS may cite it only in an answer whose limitations explain the exclusion."
      // Fail closed: every excluded ancestor must have one of its exclusion notes quoted
      // exactly in `limitations`. The answer text alone does not count. (Display check only;
      // the excluded-number leak check belongs to the B6/T1 runtime gate.)
      const unexplained = exclusion.filter((x) => !x.notes.some((n) => lims.some((l) => typeof l === "string" && l.includes(n.note))));
      if (unexplained.length) {
        problems.push(`Citation ${c.finding_id} depends on excluded ${unexplained.map((x) => x.finding.id).join(", ")}, but the answer's limitations do not give that exclusion reason (S9).`);
      }
      citations.push({ citation: c, finding: f, role: "exclusion_explanation", exclusion });
    } else {
      const trace = traceSupport(f, findingsById);
      if (!trace.supported) problems.push(`Citation ${c.finding_id} does not trace to usable evidence: ${trace.reasons.join(" ")}`);
      citations.push({ citation: c, finding: f, role: "evidence", exclusion: [] });
    }
  }
  return { problems: [...new Set(problems)], citations };
}

/** Render a reviewed answer. */
export function answerView(res, findingsById) {
  const { problems, citations } = reviewAnswer(res, findingsById);
  if (problems.length) {
    return statePanel({ kind: "error", title: "Answer withheld by dashboard check", message: problems.join(" ") });
  }
  const mode = MODES[res.mode];
  const evidence = citations.filter((c) => c.role === "evidence");
  const explanations = citations.filter((c) => c.role === "exclusion_explanation");
  const citeList = (list) =>
    h(
      "ul",
      { class: "sources" },
      list.map(({ citation, finding, exclusion }) =>
        h(
          "li",
          { class: "citation" },
          h("p", { class: "finding-head" }, evidenceBadge(finding.evidence_class), h("a", { href: `#/explorer?q=${encodeURIComponent(finding.id)}` }, finding.id), finding.fixture ? fixtureBadge() : null),
          exclusion.length
            ? h("p", { class: "small warn-text" }, "Cited only to explain an exclusion. Not evidence for a conclusion. Excluded: ", exclusion.map((x) => x.finding.id).join(", "))
            : null,
          h("ul", { class: "plain" }, sourceItem(citation.source)),
        ),
      ),
    );
  return h(
    "div",
    { class: "answer" },
    h("p", { class: "finding-head" }, h("span", { class: `badge mode-${res.mode}`, title: mode.description }, mode.label), res.fixture ? fixtureBadge() : null),
    h("p", { class: "small muted" }, "Generated by FlameGuard-SI. Not a NASA statement."),
    h("p", { class: "answer-text" }, res.answer),
    h("h3", null, "Limitations"),
    res.limitations.length ? h("ul", null, res.limitations.map((l) => h("li", null, l))) : h("p", { class: "muted" }, "None stated (no evidence found)."),
    evidence.length ? [h("h3", null, `Evidence cited (${evidence.length})`), citeList(evidence)] : null,
    explanations.length ? [h("h3", null, `Cited to explain exclusions (${explanations.length})`), citeList(explanations)] : null,
  );
}

/** @param {ReturnType<import("../store.js").createStore>} store */
export function renderAssistantPanel(store) {
  const out = h("div", { "aria-live": "polite" });
  const input = h("textarea", { id: "ask-q", rows: "3", maxlength: "2000", placeholder: "Ask about the loaded evidence…" });
  const button = h("button", { type: "submit", class: "btn btn-primary" }, "Ask TARS");

  async function submit(e) {
    e.preventDefault();
    const q = input.value.trim();
    if (!q) return;
    button.disabled = true;
    mount(out, statePanel({ kind: "loading", title: "Waiting for the assistant…" }));
    try {
      const ev = await store.evidence();
      const res = await store.source.ask(q, store.selection.ids());
      mount(out, answerView(res, ev.findingsById));
    } catch (err) {
      mount(
        out,
        isNotImplemented(err)
          ? statePanel({ kind: "not_implemented", title: "Assistant not implemented yet", message: "POST /api/assistant/ask returned HTTP 501. No answer is generated in the browser." })
          : statePanel({ kind: "error", title: "Assistant request failed", message: err.message, detail: err.code ? `code: ${err.code}` : null }),
      );
    } finally {
      button.disabled = false;
    }
  }

  return h(
    "section",
    { class: "card", "aria-labelledby": "assist-h" },
    h("h2", { id: "assist-h" }, "TARS: Traceable Analysis and Research Support"),
    h("p", { class: "small muted" }, "Answers come only from the backend, cite the findings they rely on, state their limitations, and are attributed to FlameGuard-SI. Investigations ticked for comparison are sent as the question's scope."),
    h("form", { onsubmit: submit }, h("label", { for: "ask-q", class: "field" }, h("span", null, "Question")), input, h("div", { class: "row gap" }, button)),
    out,
  );
}

