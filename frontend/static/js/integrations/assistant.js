// Assistant panel (POST /api/assistant/ask). Integration point for the
// backend assistant and the data workstream ("TARS" — not yet defined in
// spec §4). Isolated: nothing in model/ or the ranking view imports this.
//
// Rules shown in the UI: answers are attributed to FlameGuard-SI, never to
// NASA, and every answer must cite Source objects.

import { isNotImplemented } from "../api/errors.js";
import { sourceList, statePanel } from "../ui/components.js";
import { h, mount } from "../ui/dom.js";

/**
 * Check an assistant response before display.
 * @returns {string[]} problems
 */
export function reviewAnswer(res) {
  const problems = [];
  if (!res || typeof res.answer !== "string" || !res.answer.trim()) problems.push("Response has no answer text.");
  if (!res || res.generated_by !== "FlameGuard-SI") problems.push("Answer is not attributed to FlameGuard-SI.");
  if (!res || !Array.isArray(res.citations) || res.citations.length === 0) problems.push("Answer cites no sources.");
  return problems;
}

/** @param {import("../api/types.js").DataSource} source */
export function renderAssistantPanel(source) {
  const out = h("div", { "aria-live": "polite" });
  const input = h("textarea", { id: "ask-q", rows: "3", maxlength: "500", placeholder: "Ask about the loaded evidence…" });
  const button = h("button", { type: "submit", class: "btn" }, "Ask");

  async function submit(e) {
    e.preventDefault();
    const q = input.value.trim();
    if (!q) return;
    button.disabled = true;
    mount(out, statePanel({ kind: "loading", title: "Waiting for the assistant…" }));
    try {
      const res = await source.ask(q);
      const problems = reviewAnswer(res);
      if (problems.length) {
        mount(out, statePanel({ kind: "error", title: "Answer withheld", message: problems.join(" ") }));
      } else {
        mount(out, h("div", { class: "answer" }, h("p", { class: "small muted" }, "Generated by FlameGuard-SI. Not a NASA statement."), h("p", null, res.answer), h("h4", null, "Citations"), sourceList(res.citations)));
      }
    } catch (err) {
      mount(
        out,
        isNotImplemented(err)
          ? statePanel({ kind: "not_implemented", title: "Assistant not implemented yet", message: "POST /api/assistant/ask returned HTTP 501. No answer is generated in the browser." })
          : statePanel({ kind: "error", title: "Assistant request failed", message: err.message }),
      );
    } finally {
      button.disabled = false;
    }
  }

  return h(
    "section",
    { class: "card", "aria-labelledby": "assist-h" },
    h("h2", { id: "assist-h" }, "Evidence assistant ", h("span", { class: "badge planned" }, "integration point")),
    h("p", { class: "small muted" }, "Answers come only from the backend, cite their sources, and are attributed to FlameGuard-SI."),
    h("form", { onsubmit: submit }, h("label", { for: "ask-q", class: "field" }, h("span", null, "Question")), input, h("div", { class: "row gap" }, button)),
    out,
  );
}
