import { curationNotes, environmentLabel, isFixture } from "../model/evidence.js";
import { traceSupport } from "../model/trace.js";
import { evidenceBadge, findingCard, fixtureBadge, provenanceBlock, resourcePanel, statePanel } from "../ui/components.js";
import { h, mount } from "../ui/dom.js";
import { contextSelect, getContext } from "./context.js";

export const title = "Interpretation & Safety Insight";

// Limitations that apply to every view of this dashboard. These are
// FlameGuard-SI statements about method, not NASA findings.
export const LIMITATIONS = [
  "Microgravity combustion results apply to the materials, atmospheres, flow conditions, and geometries actually tested. FlameGuard-SI does not extrapolate them to untested conditions.",
  "Missing values are shown as missing. Nothing is interpolated, estimated, or filled in.",
  "Uncertainty is shown only as the source reports it. FlameGuard-SI cautions are labelled separately as FlameGuard-SI assessments.",
  "A value excluded by FlameGuard-SI is never shown as a number, and nothing derived from it supports an insight, a ranking or an assistant conclusion (rule S9).",
  "Interpretations are FlameGuard-SI analyses of measured records. They are not NASA statements or NASA endorsements.",
  "An interpretation is shown as an insight only if its full evidence chain resolves to measured records with valid provenance. Otherwise it is withheld and the reason is shown.",
  "Recorded source quotes are shown as recorded. Their verification against the source is done by the data and research workstreams, not by this page.",
  "Rankings order evidence by relevance to an application context. They are not fire-risk scores, safety ratings, alarms, or extinction predictions.",
  "Illustrative simulations (fluid and thermal transport, no combustion chemistry) never feed rankings, interpretations, or the assistant.",
];

/**
 * Classify one interpretation for display.
 * - insight: full chain to measured evidence, nothing excluded;
 * - exclusion: depends on an excluded value (S9) but is otherwise valid, so it may only explain the exclusion;
 * - withheld: any other provenance problem.
 */
export function classifyInterpretation(f, findingsById) {
  const t = traceSupport(f, findingsById);
  if (t.problems.length) return { kind: "withheld", trace: t };
  if (t.exclusionReasons.length) return { kind: "exclusion", trace: t };
  return { kind: "insight", trace: t };
}

/**
 * Card for one interpretation.
 * @param {import("../api/types.js").Finding} f
 * @param {Map<string, import("../api/types.js").Finding>} findingsById
 * @param {import("../api/types.js").Investigation | undefined} inv
 */
export function interpretationCard(f, findingsById, inv) {
  const { kind, trace } = classifyInterpretation(f, findingsById);
  const where = h("span", { class: "muted small" }, inv ? inv.name : f.investigation_id);

  if (kind === "withheld") {
    return h(
      "article",
      { class: "card chain withheld", "data-support": "withheld", "aria-label": `Withheld interpretation ${f.id}` },
      h("header", { class: "finding-head" }, h("span", { class: "badge err" }, "Withheld by dashboard check"), evidenceBadge("interpretation"), isFixture(f) ? fixtureBadge() : null, where, h("span", { class: "mono muted small" }, f.id)),
      h("p", { class: "state-title" }, "Not shown as a safety insight: the evidence chain is incomplete or invalid."),
      h("ul", { class: "reasons" }, trace.reasons.map((r) => h("li", null, r))),
      h("p", { class: "small muted" }, "The statement is hidden until its provenance is fixed. Inspect the record in the Evidence Explorer."),
    );
  }

  if (kind === "exclusion") {
    return h(
      "article",
      { class: "card chain exclusion", "data-support": "exclusion", "aria-label": `Exclusion explanation ${f.id}` },
      h("header", { class: "finding-head" }, h("span", { class: "badge vs vs-excluded" }, "Explains an exclusion"), evidenceBadge("interpretation"), isFixture(f) ? fixtureBadge() : null, where),
      h("p", { class: "small warn-text" }, "This interpretation depends on a value excluded by FlameGuard-SI. It explains the exclusion only and supports no safety conclusion (S9)."),
      h("p", { class: "statement" }, f.statement),
      h("p", { class: "small muted" }, "Generated by FlameGuard-SI. Not a NASA statement."),
      h("h3", { class: "subhead" }, "Excluded values and their reasons"),
      h(
        "ul",
        null,
        trace.excludedAncestors.map((x) =>
          h("li", null, h("span", { class: "mono" }, x.id), ": ", curationNotes(x).filter((n) => n.kind === "exclusion").map((n) => n.note).join(" ") || h("span", { class: "warn-text" }, "no exclusion note")),
        ),
      ),
      limitationsBlock(f),
      provenanceBlock(f, findingsById),
    );
  }

  const parents = (f.provenance?.derived_from || []).map((id) => findingsById.get(id));
  return h(
    "article",
    { class: "card chain", "data-support": "supported" },
    h("header", { class: "finding-head" }, evidenceBadge("interpretation"), isFixture(f) ? fixtureBadge() : null, where),
    h("p", { class: "statement" }, f.statement),
    h("p", { class: "small muted" }, `Generated by FlameGuard-SI. Not a NASA statement. Traced to ${trace.measuredRoots.length} measured record${trace.measuredRoots.length === 1 ? "" : "s"}.`),
    limitationsBlock(f),
    provenanceBlock(f, findingsById),
    h("h3", { class: "subhead" }, "Supporting evidence"),
    h("div", { class: "chain-links" }, parents.map((p) => findingCard(p, findingsById))),
  );
}

function limitationsBlock(f) {
  const lims = Array.isArray(f.limitations) ? f.limitations : [];
  return h(
    "div",
    { class: "limitations" },
    h("p", { class: "small" }, h("strong", null, "Limitations (FlameGuard-SI)"), f.provenance?.method ? h("span", { class: "muted" }, ` · method ${f.provenance.method} v${f.provenance.method_version || "?"}`) : null),
    lims.length ? h("ul", { class: "small" }, lims.map((l) => h("li", null, l))) : h("p", { class: "warn-text small" }, "No limitations stated."),
  );
}

/** @param {import("../main.js").ViewContext} ctx */
export function render(ctx) {
  const out = h("div", { "aria-live": "polite" });
  const explanations = h("div", null);
  const root = h(
    "section",
    { class: "view" },
    h("header", { class: "view-head" }, h("h1", { tabindex: "-1" }, title), h("p", { class: "lede" }, "Qualitative fire-safety implications, each traced to the measured records it is derived from.")),
    h("div", { class: "card row gap wrap" }, contextSelect(() => draw())),
    h("section", { id: "implications", class: "anchor", "aria-labelledby": "impl-h" }, h("h2", { id: "impl-h" }, "Implications and supporting evidence"), out),
    h("section", { class: "anchor", "aria-labelledby": "excl-h" }, h("h2", { id: "excl-h" }, "Exclusion explanations"), explanations),
    h("section", { id: "limitations", class: "card limits anchor", "aria-labelledby": "lim-h" }, h("h2", { id: "lim-h" }, "Scientific limitations and uncertainty"), h("ul", null, LIMITATIONS.map((l) => h("li", null, l)))),
  );

  async function draw() {
    mount(out, statePanel({ kind: "loading", title: "Loading interpretations…" }));
    const ev = await ctx.store.evidence();
    if (ev.findings.state !== "ready") {
      mount(out, resourcePanel(ev.findings, "Findings", "GET /api/findings"));
      mount(explanations);
      return;
    }
    const context = getContext();
    const invs = ev.investigations.state === "ready" ? ev.investigations.data : [];
    const invOf = (f) => invs.find((i) => i.id === f.investigation_id);
    const interps = ev.findings.data.filter((f) => f.evidence_class === "interpretation");
    const classified = interps.map((f) => ({ f, ...classifyInterpretation(f, ev.findingsById) }));

    // Context insights: the interpretation's OWN relevant_environments (contract v0.2.0).
    const forContext = classified.filter((c) => c.kind !== "exclusion" && (c.f.relevant_environments || []).includes(context));
    const untagged = classified.filter((c) => c.kind === "insight" && !(c.f.relevant_environments || []).length).length;
    const withheld = forContext.filter((c) => c.kind === "withheld").length;

    mount(
      out,
      forContext.length === 0
        ? statePanel({
            kind: "empty",
            title: `No interpretations argued to apply to ${environmentLabel(context)}`,
            message: "No interpretation finding lists this environment in its relevant_environments. FlameGuard-SI does not write implications without supporting evidence.",
          })
        : null,
      withheld ? h("p", { class: "alert alert-warn", role: "status" }, `${withheld} of ${forContext.length} interpretation${forContext.length === 1 ? "" : "s"} withheld because the evidence chain is incomplete or invalid.`) : null,
      forContext.map((c) => interpretationCard(c.f, ev.findingsById, invOf(c.f))),
      untagged ? h("p", { class: "small muted" }, `${untagged} supported interpretation${untagged === 1 ? " has" : "s have"} no environment tag and ${untagged === 1 ? "is" : "are"} not shown as a context insight.`) : null,
    );
    const excl = classified.filter((c) => c.kind === "exclusion");
    mount(explanations, excl.length ? excl.map((c) => interpretationCard(c.f, ev.findingsById, invOf(c.f))) : h("p", { class: "muted" }, "No interpretation depends on an excluded value."));
  }

  draw();
  return root;
}
