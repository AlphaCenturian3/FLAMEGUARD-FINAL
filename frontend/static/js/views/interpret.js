import { environmentLabel, isFixture } from "../model/evidence.js";
import { traceSupport } from "../model/trace.js";
import { evidenceBadge, findingCard, fixtureBadge, provenanceBlock, resourcePanel, statePanel } from "../ui/components.js";
import { h, mount } from "../ui/dom.js";
import { contextSelect, getContext } from "./context.js";

export const title = "Interpretation & Safety Insight";

// Limitations that apply to every view of this dashboard. These are
// FlameGuard-SI statements about method, not NASA findings.
export const LIMITATIONS = [
  "Microgravity combustion results apply to the materials, atmospheres, flow conditions, and geometries actually tested. FlameGuard-SI does not extrapolate them to untested conditions.",
  "Missing values are shown as missing. Nothing is interpolated, estimated, or filled in.",
  "Uncertainty is displayed exactly as the source reports it. Where a source reports none, none is shown.",
  "Interpretations are FlameGuard-SI analyses of measured records. They are not NASA statements or NASA endorsements.",
  "An interpretation is shown as an insight only if its full evidence chain resolves to measured records with valid provenance. Otherwise it is withheld and the reason is shown.",
  "Rankings order evidence by relevance to an application context. They are not fire-risk scores, safety ratings, alarms, or extinction predictions.",
  "Illustrative simulations (fluid and thermal transport, no combustion chemistry) never feed rankings, interpretations, or the assistant.",
  "Spatial frequency is reported in cycles/pixel unless a verified spatial calibration exists.",
];

/**
 * Card for one interpretation. Unsupported chains are withheld: the
 * statement is not displayed, only the reasons.
 * @param {import("../api/types.js").Finding} f
 * @param {Map<string, import("../api/types.js").Finding>} findingsById
 * @param {import("../api/types.js").Investigation | undefined} inv
 */
export function interpretationCard(f, findingsById, inv) {
  const trace = traceSupport(f, findingsById);
  const where = h("span", { class: "muted small" }, inv ? inv.name : f.investigation_id);

  if (!trace.supported) {
    return h(
      "article",
      { class: "card chain withheld", "data-support": "withheld", "aria-label": `Withheld interpretation ${f.id}` },
      h("header", { class: "finding-head" }, h("span", { class: "badge err" }, "Withheld"), evidenceBadge("interpretation"), isFixture(f) ? fixtureBadge() : null, where, h("span", { class: "mono muted small" }, f.id)),
      h("p", { class: "state-title" }, "Not shown as a safety insight: the evidence chain is incomplete or invalid."),
      h("ul", { class: "reasons" }, trace.reasons.map((r) => h("li", null, r))),
      h("p", { class: "small muted" }, "The statement is hidden until its provenance is fixed. Inspect the record in the Evidence Explorer."),
    );
  }

  const parents = (f.provenance?.derived_from || []).map((id) => findingsById.get(id));
  return h(
    "article",
    { class: "card chain", "data-support": "supported" },
    h("header", { class: "finding-head" }, evidenceBadge("interpretation"), isFixture(f) ? fixtureBadge() : null, where),
    h("p", { class: "statement" }, f.statement),
    h("p", { class: "small muted" }, `Generated by FlameGuard-SI. Not a NASA statement. Traced to ${trace.measuredRoots.length} measured record${trace.measuredRoots.length === 1 ? "" : "s"}.`),
    provenanceBlock(f, findingsById),
    h("h3", { class: "subhead" }, "Supporting evidence"),
    h("div", { class: "chain-links" }, parents.map((p) => findingCard(p, findingsById))),
  );
}

/** @param {import("../main.js").ViewContext} ctx */
export function render(ctx) {
  const out = h("div", { "aria-live": "polite" });
  const root = h(
    "section",
    { class: "view" },
    h(
      "header",
      { class: "view-head" },
      h("h1", { tabindex: "-1" }, title),
      h("p", { class: "lede" }, "Qualitative fire-safety implications, each traced to the measured records it is derived from."),
    ),
    h("div", { class: "card row gap wrap" }, contextSelect(() => draw())),
    h("section", { id: "implications", class: "anchor", "aria-labelledby": "impl-h" }, h("h2", { id: "impl-h" }, "Implications and supporting evidence"), out),
    h(
      "section",
      { id: "limitations", class: "card limits anchor", "aria-labelledby": "lim-h" },
      h("h2", { id: "lim-h" }, "Scientific limitations and uncertainty"),
      h("ul", null, LIMITATIONS.map((l) => h("li", null, l))),
    ),
  );

  async function draw() {
    mount(out, statePanel({ kind: "loading", title: "Loading interpretations…" }));
    const ev = await ctx.store.evidence();
    if (ev.findings.state !== "ready") {
      mount(out, resourcePanel(ev.findings, "Findings", "GET /api/findings"));
      return;
    }
    const context = getContext();
    const invs = ev.investigations.state === "ready" ? ev.investigations.data : [];
    const relevant = new Set(invs.filter((i) => (i.relevant_environments || []).includes(context)).map((i) => i.id));
    const interps = ev.findings.data.filter((f) => f.evidence_class === "interpretation" && relevant.has(f.investigation_id));

    if (interps.length === 0) {
      mount(
        out,
        statePanel({
          kind: "empty",
          title: `No interpretations for ${environmentLabel(context)}`,
          message: "No interpretation finding is linked to an investigation tagged with this environment. FlameGuard-SI does not write implications without supporting evidence.",
        }),
      );
      return;
    }

    const cards = interps.map((f) => interpretationCard(f, ev.findingsById, invs.find((i) => i.id === f.investigation_id)));
    const withheld = cards.filter((c) => c.dataset.support === "withheld").length;
    mount(
      out,
      withheld ? h("p", { class: "alert alert-warn", role: "status" }, `${withheld} of ${cards.length} interpretation${cards.length === 1 ? "" : "s"} withheld because the evidence chain is incomplete or invalid.`) : null,
      cards,
    );
  }

  draw();
  return root;
}
