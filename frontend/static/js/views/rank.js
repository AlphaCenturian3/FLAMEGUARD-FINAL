import { environmentLabel, isFixture } from "../model/evidence.js";
import { reviewRankings } from "../model/ranking.js";
import { resourceFromError } from "../store.js";
import { evidenceBadge, fixtureBadge, resourcePanel, statePanel } from "../ui/components.js";
import { h, mount } from "../ui/dom.js";
import { contextSelect, getContext } from "./context.js";

export const title = "Ranking";

/** @param {import("../main.js").ViewContext} ctx */
export function render(ctx) {
  const out = h("div", { "aria-live": "polite" });
  const root = h(
    "section",
    { class: "view" },
    h(
      "header",
      { class: "view-head" },
      h("h1", { tabindex: "-1" }, title),
      h("p", { class: "lede" }, "Investigations ordered by relevance to a crewed environment. Ranks, scores and criteria come only from the FlameGuard-SI backend; this page never computes, checks or re-orders them."),
    ),
    h("div", { class: "card row gap wrap" }, contextSelect(() => load()), h("p", { class: "small muted grow" }, "A relevance ordering of evidence. Not a fire-risk score or a safety rating.")),
    h(
      "section",
      { class: "card", "aria-labelledby": "rules-h" },
      h("h2", { id: "rules-h" }, "What this page shows and withholds"),
      h(
        "ul",
        null,
        h("li", null, "Criteria, weights and criterion scores exactly as the backend returns them, in the backend's rank order."),
        h("li", null, "Every input must resolve to a loaded ", evidenceBadge("measured"), " or ", evidenceBadge("interpretation"), " finding with the declared class."),
        h("li", null, "An item is withheld by the dashboard check, with the reason, if an input is unresolved, mis-declared, excluded by FlameGuard-SI, or depends on an excluded value at any depth (S9)."),
      ),
    ),
    out,
  );

  async function load() {
    const context = getContext();
    mount(out, statePanel({ kind: "loading", title: `Requesting ranking for ${environmentLabel(context)}…` }));
    const ev = await ctx.store.evidence();
    let resource;
    try {
      resource = { state: "ready", data: await ctx.store.source.getRankings(context) };
    } catch (err) {
      resource = resourceFromError(err);
    }
    if (getContext() !== context) return; // a newer request superseded this one
    if (resource.state !== "ready") {
      mount(out, resourcePanel(resource, "Rankings", `GET /api/rankings?context=${context}`));
      return;
    }
    const data = resource.data;
    const { criteria, accepted, rejected, notRanked } = reviewRankings(data, ev.findingsById);
    const invName = (id) => (ev.investigations.state === "ready" ? ev.investigations.data.find((i) => i.id === id)?.name : null) || id;
    const critName = (id) => criteria.find((c) => c.id === id)?.description || id;

    mount(
      out,
      h(
        "section",
        { class: "card", "aria-labelledby": "crit-h" },
        h("h2", { id: "crit-h" }, "Criteria ", data.fixture ? fixtureBadge() : null),
        h("p", { class: "small muted" }, `Criteria version ${data.criteria_version || "not stated"} · context ${environmentLabel(data.context)} · generated by ${data.generated_by || "not stated"}`),
        h(
          "div",
          { class: "table-wrap", tabindex: "0", role: "region", "aria-label": "Ranking criteria" },
          h("table", null, h("thead", null, h("tr", null, h("th", { scope: "col" }, "Criterion"), h("th", { scope: "col" }, "Weight"))), h("tbody", null, criteria.map((c) => h("tr", null, h("th", { scope: "row" }, c.description, h("div", { class: "mono small muted" }, c.id)), h("td", { class: "mono" }, String(c.weight)))))),
        ),
      ),
      accepted.length === 0 && rejected.length === 0 ? statePanel({ kind: "empty", title: `No ranked investigations for ${environmentLabel(context)}` }) : null,
      accepted.length
        ? h(
            "ol",
            { class: "ranking", "aria-label": "Ranked investigations, in backend order" },
            accepted.map(({ item }) =>
              h(
                "li",
                { class: "card rank-item" },
                h("div", { class: "rank-pos", "aria-hidden": "true" }, String(item.rank)),
                h(
                  "div",
                  { class: "grow" },
                  h("h3", null, h("span", { class: "sr-only" }, `Rank ${item.rank}: `), invName(item.investigation_id)),
                  h("p", null, h("span", { class: "muted" }, "Backend score: "), h("strong", { class: "mono" }, String(item.score)), h("span", { class: "muted small" }, " (relative ordering, not a risk value)")),
                  h("p", null, h("span", { class: "muted" }, "Rationale (FlameGuard-SI): "), item.rationale),
                  h(
                    "div",
                    { class: "table-wrap", tabindex: "0", role: "region", "aria-label": `Criterion scores for ${invName(item.investigation_id)}` },
                    h(
                      "table",
                      { class: "small" },
                      h("thead", null, h("tr", null, h("th", { scope: "col" }, "Criterion"), h("th", { scope: "col" }, "Score"), h("th", { scope: "col" }, "Input findings"))),
                      h(
                        "tbody",
                        null,
                        item.criterion_scores.map((cs) =>
                          h(
                            "tr",
                            null,
                            h("th", { scope: "row" }, critName(cs.criterion_id)),
                            h("td", { class: "mono" }, String(cs.score)),
                            h("td", null, cs.inputs.length ? cs.inputs.map((i) => h("span", { class: "chip" }, evidenceBadge(i.evidence_class), " ", i.finding_id, isFixture(ev.findingsById.get(i.finding_id)) ? [" ", fixtureBadge()] : null)) : h("span", { class: "muted" }, "none")),
                          ),
                        ),
                      ),
                    ),
                  ),
                ),
              ),
            ),
          )
        : null,
      rejected.length
        ? h(
            "section",
            { class: "card alert-warn" },
            h("h3", null, `Withheld by dashboard check (${rejected.length})`),
            h("ul", null, rejected.map(({ item, problems }) => h("li", null, h("strong", null, item?.investigation_id || "unknown"), `: ${problems.join(" ")}`))),
          )
        : null,
      notRanked.length
        ? h(
            "section",
            { class: "card" },
            h("h3", null, `Not ranked for ${environmentLabel(context)} (${notRanked.length})`),
            h("ul", null, notRanked.map((x) => h("li", null, h("strong", null, invName(x.investigation_id)), `: ${x.reason}`))),
          )
        : null,
    );
  }

  load();
  return root;
}
