# --- Synthetic outcomes: the generated rules ---


def test_generator_adds_one_rule_per_outcome(synthetic):
    rules = synthetic[1].schema["allOf"]
    ct = next(
        r
        for r in rules
        if r.get("if", {}).get("properties", {}).get("comparable", {}).get("const") is True
    )
    tagged = [
        r["x-generated-from-outcomes"]
        for r in ct["then"]["allOf"]
        if "x-generated-from-outcomes" in r
    ]
    assert tagged == [SYN_A, SYN_B]


def test_listed_outcome_needs_a_test_id(synthetic):
    finding_v = synthetic[0]
    finding_v.validate(_finding(test_id="T-1", test_outcome=SYN_A))
    _rejects(finding_v, _finding(test_id=None, test_outcome=SYN_A))
    doc = _finding(test_outcome=SYN_A)
    del doc["test_id"]
    _rejects(finding_v, doc)


def test_unlisted_outcome_is_rejected(synthetic):
    for value in ("SYNTHETIC-OUTCOME-C", "synthetic-outcome-a", "", "Extinction"):
        _rejects(synthetic[0], _finding(test_id="T-1", test_outcome=value))


def test_same_outcome_rows_can_be_comparable(synthetic):
    synthetic[1].validate(_comparison([_row("T-1", SYN_A), _row("T-2", SYN_A)]))
    synthetic[1].validate(_comparison([_row("T-1", SYN_B), _row("T-2", SYN_B)]))


@pytest.mark.parametrize(
    ("rows", "why"),
    [
        ([_row("T-1", SYN_A), _row("T-2", SYN_B)], "different outcomes"),
        ([_row("T-1", SYN_B), _row("T-2", SYN_A)], "different outcomes, reversed"),
        ([_row("T-1", SYN_A), _row("T-2", SYN_A), _row("T-3", SYN_B)], "one odd row out"),
        ([_row("T-1", SYN_A), _row("T-2", None)], "partially reported"),
        ([_row("T-1", SYN_A), _row(None, None)], "outcome on one row, bare row on the other"),
        ([_row("T-1", None), _row("T-2", None)], "test_id without outcome"),
        ([_row("T-1", SYN_A), _row("T-2", SYN_A), _row("T-3", None)], "third row unreported"),
    ],
    ids=lambda v: v if isinstance(v, str) else "rows",
)
def test_mixed_missing_or_partial_outcomes_cannot_be_comparable(synthetic, rows, why):
    cmp_v = synthetic[1]
    _rejects(cmp_v, _comparison(rows, comparable=True))
    cmp_v.validate(_comparison(rows, comparable=False))  # the honest answer is always allowed


def test_legacy_rows_without_test_identity_are_unaffected(synthetic, real):
    for cmp_v in (synthetic[1], real[1]):
        cmp_v.validate(_comparison([_row(None, None), _row(None, None)]))
        legacy = [
            {
                k: v
                for k, v in _row(None, None, f"f{i}").items()
                if k not in ("test_id", "test_outcome")
            }
            for i in range(2)
        ]
        cmp_v.validate(_comparison(legacy))


def test_comparison_rows_reject_free_text_outcomes(synthetic):
    _rejects(
        synthetic[1],
        _comparison([_row("T-1", "different outcome"), _row("T-2", "different outcome")]),
    )


# --- Generator behaviour ---


def test_generator_is_idempotent_and_rejects_bad_vocabularies(tmp_path):
    dest = tmp_path / "contracts"
    shutil.copytree(ROOT / "contracts", dest, ignore=shutil.ignore_patterns("__pycache__"))
    script = str(dest / "build_outcome_rules.py")
    registry = json.loads((dest / "outcomes.json").read_text(encoding="utf-8"))
    for bad in ([SYN_A, SYN_A], [""], [3]):
        _write_json(dest / "outcomes.json", {**registry, "outcomes": bad})
        done = subprocess.run([sys.executable, script], capture_output=True, text=True)  # noqa: S603
        assert done.returncode != 0
    _write_json(dest / "outcomes.json", {**registry, "outcomes": [SYN_A]})
    assert subprocess.run([sys.executable, script], capture_output=True).returncode == 0  # noqa: S603
    first = (dest / "schemas" / "comparison.schema.json").read_text(encoding="utf-8")
    assert subprocess.run([sys.executable, script], capture_output=True).returncode == 0  # noqa: S603
    assert (dest / "schemas" / "comparison.schema.json").read_text(encoding="utf-8") == first
    assert subprocess.run([sys.executable, script, "--check"], capture_output=True).returncode == 0  # noqa: S603
