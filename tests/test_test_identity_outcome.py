"""v0.2.2: structured test identity and outcome (schema side of S5).

The committed outcome vocabulary is EMPTY and UNCONFIRMED, so against the real contract no
outcome string is valid. To test the positive paths without inventing scientific values, a
fixture copies contracts/ into a temp folder, writes clearly SYNTHETIC outcome values, runs the
REAL generator (contracts/build_outcome_rules.py) there, and validates against the result.
"""

import copy
import json
import shutil
import subprocess
import sys
from pathlib import Path

import pytest
from jsonschema import Draft202012Validator, FormatChecker, ValidationError
from referencing import Registry, Resource

ROOT = Path(__file__).resolve().parents[1]
EXAMPLES = ROOT / "contracts" / "examples"
SYN_A, SYN_B = "SYNTHETIC-OUTCOME-A", "SYNTHETIC-OUTCOME-B"


def _write_json(path: Path, doc) -> None:
    text = json.dumps(doc)
    path.write_text(text, encoding="utf-8")


def _load(name):
    return json.loads((EXAMPLES / name).read_text(encoding="utf-8"))


def _validators(contracts_dir: Path):
    schemas = contracts_dir / "schemas"
    docs = [
        json.loads(p.read_text(encoding="utf-8")) for p in sorted(schemas.glob("*.schema.json"))
    ]
    registry = Registry().with_resources([(d["$id"], Resource.from_contents(d)) for d in docs])

    def make(name):
        schema = json.loads((schemas / name).read_text(encoding="utf-8"))
        return Draft202012Validator(schema, registry=registry, format_checker=FormatChecker())

    return make("finding.schema.json"), make("comparison.schema.json")


@pytest.fixture(scope="module")
def real():
    return _validators(ROOT / "contracts")


@pytest.fixture(scope="module")
def synthetic(tmp_path_factory):
    """A copy of contracts/ with two SYNTHETIC outcomes, generated by the real script."""
    dest = tmp_path_factory.mktemp("synthetic") / "contracts"
    shutil.copytree(ROOT / "contracts", dest, ignore=shutil.ignore_patterns("__pycache__"))
    registry = json.loads((dest / "outcomes.json").read_text(encoding="utf-8"))
    registry["outcomes"] = [SYN_A, SYN_B]
    _write_json(dest / "outcomes.json", registry)
    done = subprocess.run(  # noqa: S603
        [sys.executable, str(dest / "build_outcome_rules.py")], capture_output=True, text=True
    )
    assert done.returncode == 0, done.stderr
    return _validators(dest)


def _rejects(validator, doc):
    with pytest.raises(ValidationError):
        validator.validate(doc)


def _finding(**fields):
    doc = copy.deepcopy(_load("finding.measured_test_identity.example.json"))
    doc.update(fields)
    return doc


def _row(tid, outcome, fid=None):
    base = _load("comparison.test_identity.example.json")["rows"][0]
    row = {**copy.deepcopy(base), "test_id": tid, "test_outcome": outcome}
    row["finding_id"] = fid or f"fixture-finding-{(tid or 'none').lower()}"
    return row


def _comparison(rows, comparable=True):
    doc = copy.deepcopy(_load("comparison.test_identity.example.json"))
    doc["rows"] = rows
    doc["comparable"] = comparable
    doc["non_comparable_reasons"] = [] if comparable else ["FIXTURE reason"]
    return doc


# --- Committed contract: the gate ---


def test_outcome_vocabulary_is_unconfirmed_and_empty_so_no_outcome_is_valid(real):
    finding_v, _ = real
    registry = json.loads((ROOT / "contracts" / "outcomes.json").read_text(encoding="utf-8"))
    assert registry["outcomes"] == [] and registry["status"] == "UNCONFIRMED"
    for value in ("Extinction", "Disruption", SYN_A, "", "extinguished"):
        _rejects(finding_v, _finding(test_outcome=value))


def test_confirmed_values_require_a_recorded_confirmation():
    """Nobody can add outcome values without saying who confirmed them, and when."""
    registry = json.loads((ROOT / "contracts" / "outcomes.json").read_text(encoding="utf-8"))
    assert (
        registry["outcomes_version"]
        == json.loads((ROOT / "contracts" / "vocabulary.json").read_text(encoding="utf-8"))[
            "vocabulary_version"
        ]
    )
    if registry["outcomes"]:
        assert registry["status"] == "CONFIRMED"
        assert registry.get("confirmed_by") and registry.get("confirmed_on")


def test_committed_schemas_match_the_generator():
    done = subprocess.run(  # noqa: S603
        [sys.executable, str(ROOT / "contracts" / "build_outcome_rules.py"), "--check"],
        capture_output=True,
        text=True,
    )
    assert done.returncode == 0, done.stdout


def test_a_row_with_a_test_id_and_no_outcome_can_never_be_comparable_today(real):
    _, cmp_v = real
    rows = [_row("T-1", None), _row("T-2", None)]
    cmp_v.validate(_comparison(rows, comparable=False))  # allowed, with a reason
    _rejects(cmp_v, _comparison(rows, comparable=True))


